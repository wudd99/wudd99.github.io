"""Build the synchronous SVG starfield generator from the editable vector artwork."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET
ET.register_namespace('', 'http://www.w3.org/2000/svg')
root = Path(__file__).resolve().parents[1]
svg = ET.fromstring((root / 'static/images/soft-tile.svg').read_text())
ns = {'s': 'http://www.w3.org/2000/svg'}
def clean(e):
    return ET.tostring(e, encoding='unicode').replace(' xmlns="http://www.w3.org/2000/svg"', '').strip()
defs = clean(svg.find('s:defs', ns))
motifs = []
for e in svg.findall('s:g', ns)[:4]:
    e.attrib.pop('transform', None)
    motifs.append(clean(e))
source = r'''/* Generated by scripts/build-starfield.py. Motifs come from soft-tile.svg. */
(function(){
 'use strict';
 var root=document.documentElement;
 if(root.dataset.background==='image')return;
 var defs=__DEFS__,motifs=__MOTIFS__;
 var seed;
 try{seed=crypto.getRandomValues(new Uint32Array(1))[0];}catch(e){seed=Math.floor(Math.random()*4294967296);}
 var state=seed||1;
 function random(){state^=state<<13;state^=state>>>17;state^=state<<5;return (state>>>0)/4294967296;}
 function range(a,b){return a+(b-a)*random();}
 function n(v){return Math.round(v*100)/100;}
 function shuffle(a){for(var i=a.length-1;i>0;i--){var j=Math.floor(random()*(i+1)),v=a[i];a[i]=a[j];a[j]=v;}return a;}
 function point(x,y,r){return '<circle cx="'+n(x)+'" cy="'+n(y)+'" r="'+n(r)+'"/>';}
 function glow(x,y,violet){return '<g transform="translate('+n(x)+' '+n(y)+')"><circle r="'+(violet?10:12)+'" fill="url(#'+(violet?'violet-light':'starlight')+')"/><path d="M0-6 1.1-1.1 6 0 1.1 1.1 0 6-1.1 1.1-6 0-1.1-1.1Z" fill="'+(violet?'#b2aed7':'#a4c8e5')+'" fill-opacity=".55"/>'+point(0,0,1.2).replace('/>',' fill="#fff" fill-opacity=".9"/>')+'</g>';}
 var artwork=[],bodies=[],clusters=[],order=shuffle([0,1,2,3]),width=1600,height=1280;
 function distance(x,y,b){var dx=Math.abs(x-b.x),dy=Math.abs(y-b.y);return Math.hypot(Math.min(dx,width-dx),Math.min(dy,height-dy));}
 function axisDistance(a,b,size){var d=Math.abs(a-b);return Math.min(d,size-d);}
 // Wrap only artwork crossing an edge, so a repeating tile has no cropped seams.
 function place(x,y,r,render){
  var xs=[0],ys=[0];if(x<r)xs.push(width);if(x>width-r)xs.push(-width);if(y<r)ys.push(height);if(y>height-r)ys.push(-height);
  xs.forEach(function(dx){ys.forEach(function(dy){artwork.push(render(n(x+dx),n(y+dy)));});});
 }
 // Free samples across a large tile: no cells, rows or predetermined anchors.
 // Radius-aware spacing includes neighbours across opposite tile edges.
 var planetCount=16+Math.floor(random()*4);
 for(var attempt=0;attempt<1200&&bodies.length<planetCount;attempt++){
  var kind=bodies.length<4?order[bodies.length]:Math.floor(random()*4);
  var scale=n(range(.72,1.18)),r=(kind===3?23:70)*scale,x=n(range(0,width)),y=n(range(0,height));
  if(bodies.some(function(b){return distance(x,y,b)<r+b.r+95;}))continue;
  // Reject accidental alignments of three planets, without imposing a grid.
  if(bodies.filter(function(b){return axisDistance(x,b.x,width)<30;}).length>=2||bodies.filter(function(b){return axisDistance(y,b.y,height)<30;}).length>=2)continue;
  var angle=n(range(-70,70)),motif=motifs[kind];
  bodies.push({x:x,y:y,r:r});
  place(x,y,r,function(xx,yy){return '<g transform="translate('+xx+' '+yy+') rotate('+angle+') scale('+scale+')">'+motif+'</g>';});
 }
 // Constellations fill remaining space, without crowding the planets.
 var count=16+Math.floor(random()*4);
 for(var attempt=0;attempt<1500&&clusters.length<count;attempt++){
  var x=range(65,width-65),y=range(65,height-65);
  if(bodies.some(function(b){return distance(x,y,b)<b.r+83;})||clusters.some(function(c){return distance(x,y,c)<145;}))continue;
  var pts=[],nodes=3+Math.floor(random()*3),angle=range(-.7,.7),path='',dots='';
  for(var j=0;j<nodes;j++){
   var px=(j-(nodes-1)/2)*range(21,28),py=range(-17,17);
   var xx=n(x+px*Math.cos(angle)-py*Math.sin(angle)),yy=n(y+px*Math.sin(angle)+py*Math.cos(angle));
   pts.push([xx,yy]);path+=(j?' L':'M')+xx+' '+yy;dots+=point(xx,yy,range(1.1,1.8));
  }
  artwork.push('<path d="'+path+'" stroke="#8ba9c0" stroke-opacity=".24" stroke-width=".8" stroke-linejoin="round"/><g fill="#8aa9c2" fill-opacity=".32">'+dots+'</g>');
  if(clusters.length<6){var star=pts[Math.floor(random()*pts.length)];artwork.push(glow(star[0],star[1],clusters.length%2===1));}
  clusters.push({x:x,y:y});
 }
 // Small, sharp stars retain texture without recreating diffuse circular stains.
 var stars='';for(var k=0;k<65;k++){var sx=range(16,width-16),sy=range(16,height-16);stars+=point(sx,sy,range(.6,1.1));if(k<10)artwork.push('<path d="M'+n(sx-3)+' '+n(sy)+'h6m-3-3v6" stroke="#8ba9c0" stroke-opacity=".23" stroke-width=".8"/>');}
 artwork.push('<g fill="#8aa9c2" fill-opacity=".27">'+stars+'</g>');
 var svg='<svg xmlns="http://www.w3.org/2000/svg" width="'+width+'" height="'+height+'" viewBox="0 0 '+width+' '+height+'" fill="none">'+defs+artwork.join('')+'</svg>';
 root.style.setProperty('--starfield-image','url("data:image/svg+xml,'+encodeURIComponent(svg)+'")');
 root.style.setProperty('--starfield-size',width+'px '+height+'px');
 root.style.setProperty('--starfield-mobile-size',n(width*5/6)+'px '+n(height*5/6)+'px');
 root.style.setProperty('--starfield-position',n(range(-width,0))+'px '+n(range(-height,0))+'px');
})();
'''
source = source.replace('__DEFS__', json.dumps(defs)).replace('__MOTIFS__', json.dumps(motifs))
(root / 'themes/wyh_card_style/assets/js/starfield.js').write_text(source)
print('Generated js/starfield.js from SVG motifs.')
